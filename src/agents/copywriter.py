DEFAULT_PROMPT = """
Ты автор канала про нейросети. Напиши пост.
СТРОГОЕ ПРАВИЛО: Начинай текст СРАЗУ с заголовка с эмодзи. Без вступительных фраз ("Вот пост", "Привет", "Конечно").

Тема: {topic}

Длина: 600-900 символов.
Концовка: призыв сохранить в закладки 📌 или вопрос в комменты 👇.
"""


def _clean_ai_intro_chatter(text: str) -> str:
    """
    Удаляет роботизированные вступительные фразы нейросетей.
    """
    bad_prefixes = [
        "вот подборка",
        "вот пост",
        "конечно, вот",
        "конечно!",
        "держите пост",
        "предлагаю подборку",
        "вот готовый пост",
        "привет!",
        "здравствуйте",
        "публикация для вашего канала:",
        "пост для telegram-канала:",
    ]

    lines = [line.strip() for line in text.split("\n")]
    
    # Ищем первую строку, которая не является системным мусором
    cleaned_lines = []
    skip = True
    for line in lines:
        if not line:
            if not skip:
                cleaned_lines.append("")
            continue

        lower = line.lower()
        # Если строка начинается с мусорной фразы
        if skip and any(lower.startswith(p) for p in bad_prefixes):
            continue
        # Если строка содержит фразу "для твоего telegram-канала"
        if skip and ("для твоего telegram" in lower or "для вашего telegram" in lower or "для канала" in lower):
            continue

        skip = False
        cleaned_lines.append(line)

    return "\n".join(cleaned_lines).strip()


def write_post(content_plan: Dict) -> Dict:
    """
    Пишет пост для Telegram-канала.
    """
    format_ = content_plan.get("format", "Секретный промпт")
    topic = content_plan["topic"]
    news_source = content_plan.get("news", {}).get("source", "")

    prompt_template = GROWTH_PROMPTS.get(format_, DEFAULT_PROMPT)

    prompt = prompt_template.format(
        topic=topic,
        news_source=news_source,
    )

    ai_result = generate_ai_text(prompt)
    raw_text = ai_result["text"].strip()

    # 1. Очистка от вступительного мусора AI
    draft_text = _clean_ai_intro_chatter(raw_text)

    # 2. Убираем кавычки если обрамлен весь пост
    if draft_text.startswith('"') and draft_text.endswith('"'):
        draft_text = draft_text[1:-1].strip()

    # 3. Убираем markdown заголовки #
    lines = draft_text.split('\n')
    cleaned_lines = []
    for line in lines:
        if line.startswith('# ') or line.startswith('## '):
            line = line.lstrip('#').strip()
        cleaned_lines.append(line)
    draft_text = '\n'.join(cleaned_lines)

    return {
        "plan": content_plan,
        "draft_text": draft_text,
        "ai_source": ai_result["source"],
        "format": format_,
        "mode": content_plan.get("mode", "growth"),
    }